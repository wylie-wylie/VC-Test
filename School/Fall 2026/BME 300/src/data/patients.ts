import type { Assessment, BiofilmCall, ExudateAmount, InflammationCall, Patient } from "../types"

type Row = [
  date: string,
  ph: number,
  peri: number,
  ref: number,
  area: number,
  length: number,
  width: number,
  depth: number,
  granulation: number,
  slough: number,
  necrotic: number,
  epithelial: number,
  exudate: ExudateAmount,
  character: string,
  fluor: number,
  sto2: number,
  pain: number,
  periwound: string,
]

type Mark = [BiofilmCall, number, number, number, number, InflammationCall]

function visit(patientId: string, row: Row, mark: Mark): Assessment {
  const tissue = {
    granulation: row[8],
    slough: row[9],
    necrotic: row[10],
    epithelial: row[11],
  }
  const sum = tissue.granulation + tissue.slough + tissue.necrotic + tissue.epithelial
  if (sum !== 100) {
    throw new Error(`${patientId} ${row[0]} tissue fractions sum to ${sum}`)
  }
  return {
    id: `${patientId}-${row[0]}`,
    date: row[0],
    source: "clinic",
    ph: row[1],
    periwoundTempC: row[2],
    referenceTempC: row[3],
    areaCm2: row[4],
    lengthCm: row[5],
    widthCm: row[6],
    depthMm: row[7],
    tissue,
    exudate: row[12],
    exudateCharacter: row[13],
    fluorescenceIndex: row[14],
    sto2: row[15],
    painNrs: row[16],
    periwound: row[17]
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean),
    biofilm: mark[0],
    speciesCount: mark[1],
    dominantCount: mark[2],
    proteaseIndex: mark[3],
    uricAcidRelative: mark[4],
    inflammation: mark[5],
  }
}

function visits(patientId: string, rows: Row[], marks: Mark[]) {
  if (rows.length !== marks.length) {
    throw new Error(`${patientId} has ${rows.length} visits and ${marks.length} biomarker rows`)
  }
  return rows.map((row, index) => visit(patientId, row, marks[index]))
}

